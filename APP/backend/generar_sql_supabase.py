import json
import os
from datetime import datetime, timedelta

def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    seed_path = os.path.join(base_dir, "database", "seed_catalogo.json")
    out_dir = os.path.join(os.path.dirname(base_dir), "supabase", "migrations")
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "20261014000000_init_supabase_schema.sql")

    with open(seed_path, "r", encoding="utf-8") as f:
        catalogo = json.load(f)

    sql_parts = []
    sql_parts.append("-- =====================================================================")
    sql_parts.append("-- PerfumeTrending.cl — Esquema Relacional de Producción en Supabase")
    sql_parts.append("-- =====================================================================")
    sql_parts.append("-- Compatible con PostgreSQL 15+ / Supabase con RLS habilitado")
    sql_parts.append("-- Generado automáticamente para migración desde SQLite")
    sql_parts.append("-- =====================================================================\n")

    sql_parts.append("""
-- 1. Directorio de Tiendas Auditadas (Trust Score)
CREATE TABLE IF NOT EXISTS public.tiendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    url_base TEXT NOT NULL,
    trust_score INTEGER DEFAULT 85,
    badge TEXT DEFAULT 'Verificado',
    logo_emoji TEXT DEFAULT '',
    rut TEXT DEFAULT '',
    tipo_tienda TEXT DEFAULT 'Comercio Especializado',
    ssl_seguro BOOLEAN DEFAULT TRUE,
    anios_antiguedad INTEGER DEFAULT 5,
    sello_ccs BOOLEAN DEFAULT FALSE,
    reclamos_sernac TEXT DEFAULT 'Bajo',
    politica_devolucion TEXT DEFAULT '30 días de satisfacción',
    direccion_fiscal TEXT DEFAULT 'Santiago, Chile',
    puntos_seguridad INTEGER DEFAULT 25,
    puntos_legalidad INTEGER DEFAULT 25,
    puntos_garantia INTEGER DEFAULT 20,
    puntos_reputacion INTEGER DEFAULT 20,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Catálogo Maestro de Perfumes
CREATE TABLE IF NOT EXISTS public.perfumes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    marca TEXT NOT NULL,
    genero TEXT DEFAULT 'Unisex',
    tipo TEXT DEFAULT 'Eau de Parfum',
    notas TEXT NOT NULL,
    imagen_url TEXT NOT NULL,
    es_arabe BOOLEAN DEFAULT FALSE,
    en_tendencia BOOLEAN DEFAULT FALSE,
    en_remate BOOLEAN DEFAULT FALSE,
    precio_referencia INTEGER NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Registro Histórico de Precios y Stock (Time-Series)
CREATE TABLE IF NOT EXISTS public.precios_registro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT NOT NULL REFERENCES public.perfumes (id) ON DELETE CASCADE,
    tienda_id BIGINT NOT NULL REFERENCES public.tiendas (id) ON DELETE CASCADE,
    precio_actual INTEGER NOT NULL,
    precio_normal INTEGER NOT NULL,
    en_stock BOOLEAN DEFAULT TRUE,
    volumen_ml INTEGER DEFAULT 100,
    url_producto TEXT NOT NULL,
    fecha_registro TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Métricas de Tendencias Sociales (Módulo Hype Radar)
CREATE TABLE IF NOT EXISTS public.tendencias_metricas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT REFERENCES public.perfumes (id) ON DELETE CASCADE,
    menciones_semanales INTEGER DEFAULT 0,
    tasa_crecimiento NUMERIC(5,2) DEFAULT 0.0,
    score_hype INTEGER DEFAULT 50,
    plataforma TEXT DEFAULT 'YouTube',
    fecha_analisis TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Logs y Auditoría de Scraping (ETL Tracker)
CREATE TABLE IF NOT EXISTS public.scraping_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_scraper TEXT NOT NULL,
    tienda_nombre TEXT,
    productos_procesados INTEGER DEFAULT 0,
    productos_nuevos INTEGER DEFAULT 0,
    precios_actualizados INTEGER DEFAULT 0,
    estado TEXT DEFAULT 'EXITOSO',
    mensaje_detalle TEXT,
    fecha_ejecucion TIMESTAMPTZ DEFAULT NOW()
);

-- Índices B-Tree de Alto Rendimiento
CREATE INDEX IF NOT EXISTS idx_precios_perfume ON public.precios_registro(perfume_id);
CREATE INDEX IF NOT EXISTS idx_precios_tienda ON public.precios_registro(tienda_id);
CREATE INDEX IF NOT EXISTS idx_precios_fecha ON public.precios_registro(fecha_registro);
CREATE INDEX IF NOT EXISTS idx_precios_volumen ON public.precios_registro(perfume_id, volumen_ml);
CREATE INDEX IF NOT EXISTS idx_precios_stock_act ON public.precios_registro(en_stock, precio_actual);
CREATE INDEX IF NOT EXISTS idx_perfumes_marca ON public.perfumes(marca);
CREATE INDEX IF NOT EXISTS idx_perfumes_genero ON public.perfumes(genero);
CREATE INDEX IF NOT EXISTS idx_perfumes_arabe ON public.perfumes(es_arabe);
CREATE INDEX IF NOT EXISTS idx_tiendas_trust ON public.tiendas(trust_score DESC);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.tiendas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.perfumes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.precios_registro ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tendencias_metricas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scraping_logs ENABLE ROW LEVEL SECURITY;

-- Políticas RLS Permisivas para App Web & Scrapers Autónomos
DROP POLICY IF EXISTS "Lectura publica tiendas" ON public.tiendas;
CREATE POLICY "Lectura publica tiendas" ON public.tiendas FOR SELECT USING (true);
DROP POLICY IF EXISTS "Escritura tiendas" ON public.tiendas;
CREATE POLICY "Escritura tiendas" ON public.tiendas FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Lectura publica perfumes" ON public.perfumes;
CREATE POLICY "Lectura publica perfumes" ON public.perfumes FOR SELECT USING (true);
DROP POLICY IF EXISTS "Escritura perfumes" ON public.perfumes;
CREATE POLICY "Escritura perfumes" ON public.perfumes FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Lectura publica precios" ON public.precios_registro;
CREATE POLICY "Lectura publica precios" ON public.precios_registro FOR SELECT USING (true);
DROP POLICY IF EXISTS "Escritura precios" ON public.precios_registro;
CREATE POLICY "Escritura precios" ON public.precios_registro FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Lectura publica tendencias" ON public.tendencias_metricas;
CREATE POLICY "Lectura publica tendencias" ON public.tendencias_metricas FOR SELECT USING (true);
DROP POLICY IF EXISTS "Escritura tendencias" ON public.tendencias_metricas;
CREATE POLICY "Escritura tendencias" ON public.tendencias_metricas FOR ALL USING (true) WITH CHECK (true);

-- 6. Vistas Optimizadas para Consultas de Alto Rendimiento en la App Web
CREATE OR REPLACE VIEW public.vista_catalogo AS
SELECT p.id,
       p.nombre,
       p.marca,
       p.genero,
       p.tipo,
       p.notas,
       p.imagen_url,
       p.es_arabe,
       p.en_tendencia,
       p.en_remate,
       p.precio_referencia,
       p.created_at,
       MIN(CASE WHEN pr.en_stock = TRUE AND pr.precio_actual > 0 THEN pr.precio_actual END) as mejor_precio,
       MAX(pr.fecha_registro) as ultima_actualizacion
FROM public.perfumes p
LEFT JOIN public.precios_registro pr ON p.id = pr.perfume_id
GROUP BY p.id;

CREATE OR REPLACE VIEW public.vista_precios_actuales AS
WITH ultimos_precios AS (
    SELECT DISTINCT ON (perfume_id, tienda_id)
        pr.id,
        pr.perfume_id,
        pr.tienda_id,
        pr.precio_actual,
        pr.precio_normal,
        pr.en_stock,
        COALESCE(pr.volumen_ml, 100) as volumen_ml,
        ROUND(CAST(pr.precio_actual AS NUMERIC) / GREATEST(1, COALESCE(pr.volumen_ml, 100))) as precio_por_ml,
        pr.url_producto,
        pr.fecha_registro
    FROM public.precios_registro pr
    WHERE pr.en_stock = TRUE AND pr.precio_actual > 0 AND pr.url_producto IS NOT NULL
    ORDER BY pr.perfume_id, pr.tienda_id, pr.fecha_registro DESC
)
SELECT 
    up.*,
    t.nombre as tienda_nombre,
    t.url_base,
    t.trust_score,
    t.badge,
    t.logo_emoji
FROM ultimos_precios up
JOIN public.tiendas t ON up.tienda_id = t.id;

-- Permisos de lectura pública en Vistas para PostgREST (anon y authenticated)
GRANT SELECT ON public.vista_catalogo TO anon, authenticated, service_role;
GRANT SELECT ON public.vista_precios_actuales TO anon, authenticated, service_role;

DROP POLICY IF EXISTS "Lectura publica scraping_logs" ON public.scraping_logs;
CREATE POLICY "Lectura publica scraping_logs" ON public.scraping_logs FOR SELECT USING (true);
DROP POLICY IF EXISTS "Escritura scraping_logs" ON public.scraping_logs;
CREATE POLICY "Escritura scraping_logs" ON public.scraping_logs FOR ALL USING (true) WITH CHECK (true);
""")

    # 1. Tiendas INSERTs
    sql_parts.append("\n-- POBLADO INICIAL: TIENDAS AUDITADAS")
    tiendas = catalogo.get("tiendas", [])
    for t in tiendas:
        nombre = t["nombre"].replace("'", "''")
        url_base = t["url_base"].replace("'", "''")
        trust_score = t.get("trust_score", 85)
        badge = t.get("badge", "Verificado").replace("'", "''")
        logo_emoji = t.get("logo_emoji", "").replace("'", "''")
        rut = t.get("rut", "").replace("'", "''")
        tipo_tienda = t.get("tipo_tienda", "Comercio Especializado").replace("'", "''")
        ssl = "TRUE" if t.get("ssl_seguro", 1) else "FALSE"
        anios = t.get("anios_antiguedad", 5)
        ccs = "TRUE" if t.get("sello_ccs", 0) else "FALSE"
        sernac = t.get("reclamos_sernac", "Bajo").replace("'", "''")
        devolucion = t.get("politica_devolucion", "30 días").replace("'", "''")
        direccion = t.get("direccion_fiscal", "Santiago, Chile").replace("'", "''")
        p_seg = t.get("puntos_seguridad", 25)
        p_leg = t.get("puntos_legalidad", 25)
        p_gar = t.get("puntos_garantia", 20)
        p_rep = t.get("puntos_reputacion", 20)

        sql_parts.append(
            f"INSERT INTO public.tiendas (nombre, url_base, trust_score, badge, logo_emoji, rut, tipo_tienda, ssl_seguro, anios_antiguedad, sello_ccs, reclamos_sernac, politica_devolucion, direccion_fiscal, puntos_seguridad, puntos_legalidad, puntos_garantia, puntos_reputacion) "
            f"VALUES ('{nombre}', '{url_base}', {trust_score}, '{badge}', '{logo_emoji}', '{rut}', '{tipo_tienda}', {ssl}, {anios}, {ccs}, '{sernac}', '{devolucion}', '{direccion}', {p_seg}, {p_leg}, {p_gar}, {p_rep}) "
            f"ON CONFLICT (nombre) DO UPDATE SET trust_score = EXCLUDED.trust_score, badge = EXCLUDED.badge;"
        )

    # 2. Perfumes INSERTs
    sql_parts.append("\n-- POBLADO INICIAL: CATÁLOGO DE PERFUMES")
    perfumes = catalogo.get("perfumes", [])
    for p in perfumes:
        p_id = p["id"]
        nombre = p["nombre"].replace("'", "''")
        marca = p["marca"].replace("'", "''")
        genero = p.get("genero", "Unisex").replace("'", "''")
        tipo = p.get("tipo", "Eau de Parfum").replace("'", "''")
        notas = p["notas"].replace("'", "''")
        imagen_url = p["imagen_url"].replace("'", "''")
        es_arabe = "TRUE" if p.get("es_arabe", False) else "FALSE"
        en_tendencia = "TRUE" if p.get("en_tendencia", False) else "FALSE"
        en_remate = "TRUE" if p.get("en_remate", False) else "FALSE"
        precio_ref = p["precio_referencia"]

        sql_parts.append(
            f"INSERT INTO public.perfumes (id, nombre, marca, genero, tipo, notas, imagen_url, es_arabe, en_tendencia, en_remate, precio_referencia) "
            f"OVERRIDING SYSTEM VALUE VALUES ({p_id}, '{nombre}', '{marca}', '{genero}', '{tipo}', '{notas}', '{imagen_url}', {es_arabe}, {en_tendencia}, {en_remate}, {precio_ref}) "
            f"ON CONFLICT (id) DO UPDATE SET precio_referencia = EXCLUDED.precio_referencia, imagen_url = EXCLUDED.imagen_url;"
        )

    # Ajustar secuencia de ID de perfumes
    sql_parts.append("\nSELECT setval(pg_get_serial_sequence('public.perfumes', 'id'), COALESCE(MAX(id), 1) + 1, false) FROM public.perfumes;")

    # 3. Precios Históricos
    sql_parts.append("\n-- POBLADO INICIAL: HISTÓRICO TIME-SERIES DE PRECIOS")
    dias_atras = [21, 14, 7, 3, 1, 0]
    
    for p in perfumes:
        p_id = p["id"]
        for enlace in p.get("enlaces_tiendas", []):
            t_nombre = enlace.get("tienda", "").replace("'", "''")
            precio_act = enlace.get("precio_actual", p["precio_referencia"])
            p_normal_val = enlace.get("precio_normal")
            precio_norm = p_normal_val if (p_normal_val and p_normal_val > precio_act) else precio_act
            url_prod = enlace.get("url_producto", "").replace("'", "''")
            vol_ml = enlace.get("volumen_ml", p.get("volumen_ml", 100))

            for dia in dias_atras:
                if dia == 0:
                    p_act_h = precio_act
                    p_norm_h = precio_norm
                else:
                    fluc = 1.0 + (dia * 0.004)
                    p_act_h = int(round((precio_act * fluc) / 1000) * 1000)
                    p_norm_h = precio_norm if precio_norm > precio_act else p_act_h

                fecha_expr = f"NOW() - INTERVAL '{dia} days'"

                sql_parts.append(
                    f"INSERT INTO public.precios_registro (perfume_id, tienda_id, precio_actual, precio_normal, en_stock, volumen_ml, url_producto, fecha_registro) "
                    f"SELECT {p_id}, t.id, {p_act_h}, {p_norm_h}, TRUE, {vol_ml}, '{url_prod}', {fecha_expr} "
                    f"FROM public.tiendas t WHERE t.nombre = '{t_nombre}';"
                )

    full_sql = "\n".join(sql_parts) + "\n"

    with open(out_file, "w", encoding="utf-8") as f:
        f.write(full_sql)

    print(f"Migracion generada con exito en: {out_file} ({len(full_sql)} bytes)")

if __name__ == "__main__":
    main()
