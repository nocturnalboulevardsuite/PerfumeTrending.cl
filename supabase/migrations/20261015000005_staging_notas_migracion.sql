CREATE TABLE IF NOT EXISTS public.perfume_notas_importacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT NOT NULL REFERENCES public.perfumes(id) ON DELETE RESTRICT,
    texto_original TEXT NOT NULL,
    estado TEXT NOT NULL DEFAULT 'pendiente',
    notas_revision TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT perfume_notas_importacion_estado_valido
        CHECK (estado IN ('pendiente','revisado','importado','requiere_revision')),
    CONSTRAINT perfume_notas_importacion_perfume_unico UNIQUE (perfume_id)
);

-- Poblar staging desde la columna histórica sin modificar perfumes.notas
INSERT INTO public.perfume_notas_importacion (perfume_id, texto_original)
