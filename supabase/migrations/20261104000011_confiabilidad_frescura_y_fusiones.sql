-- 1. Tabla de auditoría reversible para fusiones canónicas de perfumes duplicados
CREATE TABLE IF NOT EXISTS public.fusiones_perfumes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen BIGINT NOT NULL,
    id_destino BIGINT NOT NULL REFERENCES public.perfumes(id) ON DELETE RESTRICT,
    motivo TEXT NOT NULL,
    snapshot_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    ejecutado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_fusiones_perfumes_destino
    ON public.fusiones_perfumes (id_destino);

CREATE INDEX IF NOT EXISTS idx_fusiones_perfumes_origen
    ON public.fusiones_perfumes (id_origen);

ALTER TABLE public.fusiones_perfumes ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'fusiones_perfumes'
          AND policyname = 'fusiones_perfumes_service_role_all'
    ) THEN
        CREATE POLICY fusiones_perfumes_service_role_all
            ON public.fusiones_perfumes
            FOR ALL
            TO service_role
            USING (true)
            WITH CHECK (true);
    END IF;
END $$;

-- 2. Vista analítica de ofertas con cálculo en vivo de días sin verificar (UTC)
CREATE OR REPLACE VIEW public.ofertas_con_frescura AS
SELECT
    oa.*,
    ROUND(
        GREATEST(
            0.0,
            EXTRACT(EPOCH FROM (now() - COALESCE(oa.ultima_verificacion_exitosa, oa.updated_at, oa.created_at))) / 86400.0
        )::numeric,
        2
    ) AS dias_sin_verificar,
    CASE
        WHEN COALESCE(oa.ultima_verificacion_exitosa, oa.updated_at, oa.created_at) IS NULL THEN 'obsoleta'
        WHEN EXTRACT(EPOCH FROM (now() - COALESCE(oa.ultima_verificacion_exitosa, oa.updated_at, oa.created_at))) / 86400.0 <= 3.0 THEN 'fresca'
        WHEN EXTRACT(EPOCH FROM (now() - COALESCE(oa.ultima_verificacion_exitosa, oa.updated_at, oa.created_at))) / 86400.0 <= 7.0 THEN 'reciente'
        WHEN EXTRACT(EPOCH FROM (now() - COALESCE(oa.ultima_verificacion_exitosa, oa.updated_at, oa.created_at))) / 86400.0 <= 14.0 THEN 'desactualizada'
        ELSE 'obsoleta'
    END AS nivel_frescura
FROM public.ofertas_actuales oa;

