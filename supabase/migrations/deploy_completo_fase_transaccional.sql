-- 1. Variantes de Perfume (Presentación / SKU Físico)
CREATE TABLE IF NOT EXISTS public.variantes_perfume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT NOT NULL REFERENCES public.perfumes(id) ON DELETE RESTRICT,
    concentracion TEXT,
    volumen_ml NUMERIC(8,2),
    formato TEXT NOT NULL DEFAULT 'regular',
    identificador_externo TEXT,
    slug TEXT UNIQUE,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT variantes_volumen_positivo CHECK (volumen_ml IS NULL OR volumen_ml > 0),
    CONSTRAINT variantes_formato_no_vacio CHECK (length(trim(formato)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_variantes_perfume_perfume
    ON public.variantes_perfume (perfume_id);
CREATE INDEX IF NOT EXISTS idx_variantes_perfume_atributos
    ON public.variantes_perfume (perfume_id, volumen_ml, concentracion, formato);

-- 2. Ofertas Actuales Vivas (Snapshot de Precios y Stock por Comercio)
CREATE TABLE IF NOT EXISTS public.ofertas_actuales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variante_id BIGINT NOT NULL REFERENCES public.variantes_perfume(id) ON DELETE RESTRICT,
    tienda_id BIGINT NOT NULL REFERENCES public.tiendas(id) ON DELETE RESTRICT,
    precio_actual INTEGER,
    precio_normal INTEGER,
    en_stock BOOLEAN,
    url_producto TEXT,
    estado TEXT NOT NULL DEFAULT 'no_verificada',
    ultima_verificacion_exitosa TIMESTAMPTZ,
    ultimo_intento TIMESTAMPTZ,
    ultimo_cambio_confirmado TIMESTAMPTZ,
    fallos_consecutivos INTEGER NOT NULL DEFAULT 0,
    ultimo_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ofertas_variante_tienda_unica UNIQUE (variante_id, tienda_id),
    CONSTRAINT ofertas_precio_actual_valido CHECK (precio_actual IS NULL OR precio_actual > 0),
    CONSTRAINT ofertas_precio_normal_valido CHECK (precio_normal IS NULL OR precio_normal > 0),
    CONSTRAINT ofertas_fallos_no_negativos CHECK (fallos_consecutivos >= 0),
    CONSTRAINT ofertas_estado_valido CHECK (estado IN
        ('activa','agotada','no_verificada','retirada','requiere_revision'))
);

CREATE INDEX IF NOT EXISTS idx_ofertas_variante ON public.ofertas_actuales (variante_id);
CREATE INDEX IF NOT EXISTS idx_ofertas_tienda ON public.ofertas_actuales (tienda_id);
CREATE INDEX IF NOT EXISTS idx_ofertas_stock_precio
    ON public.ofertas_actuales (en_stock, precio_actual) WHERE estado = 'activa';
CREATE INDEX IF NOT EXISTS idx_ofertas_verificacion
    ON public.ofertas_actuales (ultima_verificacion_exitosa DESC);

-- 3. Auditoría de Ejecuciones ETL (scraping_runs)
CREATE TABLE IF NOT EXISTS public.scraping_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_scraper TEXT NOT NULL,
    tienda_id BIGINT REFERENCES public.tiendas(id) ON DELETE RESTRICT,
    estado TEXT NOT NULL DEFAULT 'iniciado',
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_fin TIMESTAMPTZ,
    productos_procesados INTEGER NOT NULL DEFAULT 0,
    ofertas_nuevas INTEGER NOT NULL DEFAULT 0,
    cambios_precio INTEGER NOT NULL DEFAULT 0,
    cambios_stock INTEGER NOT NULL DEFAULT 0,
    cambios_url INTEGER NOT NULL DEFAULT 0,
    errores INTEGER NOT NULL DEFAULT 0,
    mensaje_detalle TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT scraping_runs_estado_valido CHECK (estado IN
        ('iniciado','exitoso','parcial','fallido','cancelado')),
    CONSTRAINT scraping_runs_contadores_validos CHECK (
        productos_procesados >= 0 AND ofertas_nuevas >= 0 AND
        cambios_precio >= 0 AND cambios_stock >= 0 AND
        cambios_url >= 0 AND errores >= 0),
    CONSTRAINT scraping_runs_fechas_validas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE INDEX IF NOT EXISTS idx_scraping_runs_fecha
    ON public.scraping_runs (fecha_inicio DESC);
CREATE INDEX IF NOT EXISTS idx_scraping_runs_tienda_fecha
    ON public.scraping_runs (tienda_id, fecha_inicio DESC);

-- 4. Ampliación Aditiva del Historial (precios_registro)
ALTER TABLE public.precios_registro
    ADD COLUMN IF NOT EXISTS variante_id BIGINT
        REFERENCES public.variantes_perfume(id) ON DELETE RESTRICT;
ALTER TABLE public.precios_registro
