-- 1. Familias de Notas
CREATE TABLE IF NOT EXISTS public.familias_notas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL UNIQUE,
    emoji TEXT NOT NULL DEFAULT '',
    descripcion TEXT,
    orden INTEGER NOT NULL UNIQUE,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT familias_notas_slug_valido CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT familias_notas_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT familias_notas_orden_positivo CHECK (orden > 0)
);

-- 2. Notas Olfativas Canónicas
CREATE TABLE IF NOT EXISTS public.notas_olfativas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    familia_id BIGINT NOT NULL REFERENCES public.familias_notas(id) ON DELETE RESTRICT,
    slug TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    sinonimos TEXT[] NOT NULL DEFAULT '{}',
    descripcion TEXT,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT notas_olfativas_slug_valido CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT notas_olfativas_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT notas_olfativas_familia_nombre_unico UNIQUE (familia_id, nombre)
);

CREATE INDEX IF NOT EXISTS idx_notas_olfativas_familia_nombre
    ON public.notas_olfativas (familia_id, nombre);
CREATE INDEX IF NOT EXISTS idx_notas_olfativas_sinonimos
    ON public.notas_olfativas USING gin (sinonimos);

-- 3. Relación Perfume-Nota
CREATE TABLE IF NOT EXISTS public.perfume_notas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT NOT NULL REFERENCES public.perfumes(id) ON DELETE RESTRICT,
    nota_id BIGINT NOT NULL REFERENCES public.notas_olfativas(id) ON DELETE RESTRICT,
    etapa TEXT NOT NULL DEFAULT 'desconocida',
    fuente_tipo TEXT NOT NULL DEFAULT 'pendiente',
    fuente_url TEXT,
    confianza SMALLINT,
    verificada BOOLEAN NOT NULL DEFAULT FALSE,
    observacion_fuente TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT perfume_notas_etapa_valida
        CHECK (etapa IN ('salida','corazon','fondo','desconocida')),
    CONSTRAINT perfume_notas_fuente_valida CHECK (fuente_tipo IN
        ('fabricante','tienda','editorial','manual','comunidad','inferencia','pendiente')),
    CONSTRAINT perfume_notas_confianza_valida
        CHECK (confianza IS NULL OR confianza BETWEEN 0 AND 100),
    CONSTRAINT perfume_notas_relacion_unica UNIQUE (perfume_id, nota_id, etapa)
);

CREATE INDEX IF NOT EXISTS idx_perfume_notas_perfume_etapa
    ON public.perfume_notas (perfume_id, etapa);
CREATE INDEX IF NOT EXISTS idx_perfume_notas_nota_perfume
    ON public.perfume_notas (nota_id, perfume_id);
CREATE INDEX IF NOT EXISTS idx_perfume_notas_verificacion
    ON public.perfume_notas (verificada, fuente_tipo);

-- 4. Familias Olfativas Generales (Clasificación Macro Editorial)
CREATE TABLE IF NOT EXISTS public.familias_olfativas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    padre_id BIGINT REFERENCES public.familias_olfativas(id) ON DELETE RESTRICT,
    slug TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL UNIQUE,
    descripcion TEXT,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT familias_olfativas_slug_valido CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT familias_olfativas_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT familias_olfativas_no_auto_padre CHECK (padre_id IS NULL OR padre_id <> id)
);

CREATE INDEX IF NOT EXISTS idx_familias_olfativas_padre
    ON public.familias_olfativas (padre_id);

-- 5. Relación Perfume-Familia General
CREATE TABLE IF NOT EXISTS public.perfume_familias_olfativas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT NOT NULL REFERENCES public.perfumes(id) ON DELETE RESTRICT,
    familia_id BIGINT NOT NULL REFERENCES public.familias_olfativas(id) ON DELETE RESTRICT,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    fuente_tipo TEXT NOT NULL DEFAULT 'pendiente',
    fuente_url TEXT,
    confianza SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT perfume_familias_relacion_unica UNIQUE (perfume_id, familia_id),
    CONSTRAINT perfume_familias_fuente_valida CHECK (fuente_tipo IN
        ('fabricante','tienda','editorial','manual','comunidad','inferencia','pendiente')),
    CONSTRAINT perfume_familias_confianza_valida
        CHECK (confianza IS NULL OR confianza BETWEEN 0 AND 100)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_perfume_familia_principal
    ON public.perfume_familias_olfativas (perfume_id) WHERE es_principal = true;
CREATE INDEX IF NOT EXISTS idx_perfume_familias_familia_perfume
    ON public.perfume_familias_olfativas (familia_id, perfume_id);


