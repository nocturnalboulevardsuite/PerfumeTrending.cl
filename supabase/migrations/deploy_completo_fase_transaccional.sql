ALTER TABLE public.precios_registro
    ADD COLUMN IF NOT EXISTS scraping_run_id BIGINT
        REFERENCES public.scraping_runs(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS idx_precios_registro_variante_fecha
    ON public.precios_registro (variante_id, fecha_registro DESC);
CREATE INDEX IF NOT EXISTS idx_precios_registro_observacion
    ON public.precios_registro (observacion_id) WHERE observacion_id IS NOT NULL;


